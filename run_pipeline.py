"""
Run the whole project end to end:

    python -m src.download_data      # once: fetch the public dataset
    python run_pipeline.py           # train, evaluate, explain, report
    python run_pipeline.py --synthetic   # no internet? use generated demo data
    streamlit run app/streamlit_app.py   # then open the app
"""
from __future__ import annotations

import argparse
import json
import time

import pandas as pd

from src import business, business_plots, config, data_prep, eda, evaluate, explain, report, train


def step(title: str) -> float:
    print(f"\n== {title}")
    return time.time()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true", help="use generated demo data instead of the real CSV")
    ap.add_argument("--fast", action="store_true", help="smaller hyper-parameter search (quick check)")
    args = ap.parse_args()
    t0 = time.time()

    t = step("1/6 Loading and cleaning data")
    if args.synthetic:
        if config.RAW_FILE.exists() and not config.SYNTHETIC_MARKER.exists():
            raise SystemExit(f"{config.RAW_FILE} is real data: refusing to overwrite it with demo data. "
                             "Run without --synthetic, or move the file away first.")
        from src.synthetic import generate
        config.RAW_DIR.mkdir(parents=True, exist_ok=True)
        generate(n=7000).to_csv(config.RAW_FILE, index=False)
        config.SYNTHETIC_MARKER.write_text("Generated by src/synthetic.py, not real Telco data.\n")
    elif config.SYNTHETIC_MARKER.exists():
        raise SystemExit("data/raw/_SYNTHETIC_DATA.txt exists: delete it and the CSV, run "
                         "`python -m src.download_data`, then re-run (otherwise reports would say 'demo data').")
    df = data_prep.prepare()
    synthetic = config.SYNTHETIC_MARKER.exists()
    print(f"   {len(df):,} customers, churn rate {df[config.TARGET].mean():.1%}, {time.time() - t:.1f}s")

    t = step("2/6 Exploratory analysis")
    eda_paths = eda.make_plots(df)
    assoc, num = eda.categorical_association(df), eda.numeric_tests(df)
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    assoc.to_csv(config.REPORTS_DIR / "eda_categorical_tests.csv", index=False)
    num.to_csv(config.REPORTS_DIR / "eda_numeric_tests.csv", index=False)
    print(f"   {len(eda_paths)} figures, {time.time() - t:.1f}s")

    t = step("3/6 Training and comparing models")
    res = train.train(df, fast=args.fast)
    model, meta = res["model"], res["meta"]
    print(f"   selected: {meta['selected_model']}  ({time.time() - t:.0f}s)")

    t = step("4/6 Evaluating on the hold-out test set")
    a = business.Assumptions()
    scored = res["scored"]
    train_oof = scored[scored["split"] == "train"]
    thr = business.best_probability_threshold(train_oof["churn_probability"], train_oof[config.TARGET],
                                              train_oof["MonthlyCharges"], a)
    p_test = model.predict_proba(res["X_test"])[:, 1]
    m = evaluate.metrics_at(res["y_test"], p_test, thr)
    evaluate.make_plots(res["y_test"], p_test, thr, meta["selected_model"])
    deciles = evaluate.decile_table(res["y_test"], p_test)
    test_df = res["X_test"].copy()
    test_df["gender"] = df.loc[test_df.index, "gender"]      # used ONLY for the group check, never as a feature
    fair = pd.concat([evaluate.group_metrics(test_df, res["y_test"], p_test, thr, "SeniorCitizen"),
                      evaluate.group_metrics(test_df, res["y_test"], p_test, thr, "gender")])
    fair.to_csv(config.REPORTS_DIR / "fairness_check.csv", index=False)
    deciles.to_csv(config.REPORTS_DIR / "decile_table.csv", index=False)
    print(f"   AUC {m['roc_auc']:.3f}  PR-AUC {m['pr_auc']:.3f}  recall {m['recall']:.2f} @ threshold {thr:.2f}")

    t = step("5/6 Explaining the model")
    perm = explain.permutation_table(model, res["X_test"], res["y_test"])
    explain.plot_permutation(perm)
    explain.plot_shap_summary(model, res["X_test"], res["X_train"])
    perm.to_csv(config.REPORTS_DIR / "permutation_importance.csv", index=False)
    print(f"   top feature: {perm.iloc[0]['feature']}  ({time.time() - t:.0f}s)")

    t = step("6/6 Business impact, report and saved model")
    test_scored = scored[scored["split"] == "test"]
    strat = business.strategy_comparison(test_scored, a)
    strat.to_csv(config.REPORTS_DIR / "strategy_backtest.csv", index=False)
    business_plots.make_plots(test_scored, a)
    text = report.build_text(meta, m, deciles, strat, a, perm, assoc, synthetic)
    report.write(text, {"selected_model": meta["selected_model"], "test": m, "assumptions": a.__dict__,
                        "strategy_backtest": strat.to_dict("records"), "model_comparison": meta["comparison"]})
    meta["operating_threshold"] = thr
    meta["test_metrics"] = m
    meta["synthetic"] = synthetic
    train.save(res)
    config.META_FILE.write_text(json.dumps(meta, indent=2, default=float))
    print(f"\nAll done in {time.time() - t0:.0f}s. Next: streamlit run app/streamlit_app.py")


if __name__ == "__main__":
    main()
